"""
build_sharpness_report.py — aggregate results/sharpness_*.json into SHARPNESS.md
(paired diffs vs uniform per (s, arm); entropy/dispersion/off-mode diagnostics;
the b4-vs-shuffled mechanism contrast) and figures/fig5_sharpness.png (panel A:
paired dist_uni diff vs arm per s with 95% CIs; panel B: selection entropy per
arm). Predictions S1-S4 in HYPOTHESIS.md "Round 4".
"""
import os, sys, glob, json, math
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std, median, t975

ARM_ORDER = ["witness_b1_f0", "witness_b2_f0", "witness_b4_f0", "witness_topk",
             "witness_b4_shuffled"]
ARM_SHORT = {"witness_b1_f0": "β=1", "witness_b2_f0": "β=2", "witness_b4_f0": "β=4",
             "witness_topk": "top-k", "witness_b4_shuffled": "β=4 shuffled"}
S_COLORS = {0.10: "#0072B2", 0.25: "#E69F00", 0.50: "#009E73"}  # Okabe-Ito
INK, MUTED = "#333333", "#8a8a8a"


def ci95(d):
    if len(d) < 2:
        return float("nan"), float("nan")
    m, sd = mean_std(d)
    return m, t975(len(d) - 1) * sd / math.sqrt(len(d))


def pair(by, s, arm_a, arm_b, metric="dist_uni"):
    a, b = by.get((s, arm_a), {}), by.get((s, arm_b), {})
    ks = sorted(set(a) & set(b))
    return [a[k][metric] - b[k][metric] for k in ks]


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(_HERE, "results", "sharpness_*.json")))
    if not paths:
        sys.exit("no sharpness result JSONs found")
    by = defaultdict(dict)   # [(s, arm)][(seed, restart)] = row
    metas = []
    for p in paths:
        d = json.load(open(p))
        for r in d["rows"]:
            by[(r["s"], r["arm"])][(r["seed"], r["restart"])] = r
        metas.append((os.path.basename(p), d["meta"]))
    s_vals = sorted({s for s, _ in by})
    arms = [a for a in ARM_ORDER if any(a == arm for _, arm in by)]

    L = ["# Round 4 — sharpened witness selection + shuffled control", "",
         "*Generated by build_sharpness_report.py; predictions S1-S4 in "
         "HYPOTHESIS.md ('Round 4'). All stochastic arms use with-replacement "
         "k-draws + unbiased IPW gradient weights; top-k is deterministic and "
         "BIASED (documented). Metric: dist_uni (x-space).*", "",
         f"Input files ({len(metas)}):", ""]
    for name, meta in metas:
        L.append(f"- `{name}` — s_list={meta['s_list']}, arms={meta['arms']}, "
                 f"seeds={meta['seeds']}, n_restarts={meta['n_restarts']}")

    # S2/S3 table: paired diff vs uniform
    L += ["", "## Paired dist_uni diff (arm − mmd_uniform), pooled over seeds", "",
          "| s | " + " | ".join(ARM_SHORT.get(a, a) for a in arms) + " | n pairs |",
          "|---|" + "---|" * (len(arms) + 1)]
    fig_diff = {}
    for s in s_vals:
        cells, npairs = [], 0
        for a in arms:
            d = pair(by, s, a, "mmd_uniform")
            m, c = ci95(d)
            star = "*" if c == c and abs(m) > c else ""
            cells.append(f"{m:+.4f}{star} ±{c:.4f}" if d else "—")
            fig_diff[(s, a)] = (m, c)
            npairs = max(npairs, len(d))
        L.append(f"| {s:g} | " + " | ".join(cells) + f" | {npairs} |")

    # S3 direct: b4 vs shuffled
    L += ["", "## S3 — mechanism contrast: witness_b4_f0 − witness_b4_shuffled", "",
          "| s | diff | 95% CI | verdict hint |", "|---|---|---|---|"]
    for s in s_vals:
        d = pair(by, s, "witness_b4_f0", "witness_b4_shuffled")
        if d:
            m, c = ci95(d)
            star = "*" if c == c and abs(m) > c else ""
            hint = "informative selection" if (star and m < 0) else "no separation (artifact-compatible)"
            L.append(f"| {s:g} | {m:+.4f}{star} | ±{c:.4f} | {hint} |")

    # S1/S4 diagnostics
    L += ["", "## S1/S4 — selection diagnostics (mean over restarts of per-run means)", "",
          "| s | arm | sel entropy H | score max/med | score std | sel_offmode | base rate |",
          "|---|---|---|---|---|---|---|"]
    diag_ent = {}
    for s in s_vals:
        for a in ["mmd_uniform"] + arms:
            rows = list(by.get((s, a), {}).values())
            if not rows:
                continue
            def mv(k):
                v = [r[k] for r in rows if k in r and r[k] == r[k]]
                return (sum(v) / len(v)) if v else float("nan")
            diag_ent[(s, a)] = mv("sel_entropy")
            L.append(f"| {s:g} | {ARM_SHORT.get(a, a)} | {mv('sel_entropy'):.3f} | "
                     f"{mv('score_disp'):.2f} | {mv('score_std'):.4f} | "
                     f"{mv('frac_selected_offmode'):.4f} | {mv('frac_offmode'):.4f} |")
    L += ["", "`*` = 95% CI excludes 0.", ""]

    # figure
    os.makedirs(os.path.join(_HERE, "figures"), exist_ok=True)
    fig, (axA, axB) = plt.subplots(1, 2, figsize=(9.6, 4.2),
                                   gridspec_kw={"width_ratios": [1.4, 1]})
    xs = range(len(arms))
    for s in s_vals:
        ms = [fig_diff.get((s, a), (float("nan"),) * 2)[0] for a in arms]
        cs = [fig_diff.get((s, a), (float("nan"),) * 2)[1] for a in arms]
        n_pairs = max((len(pair(by, s, a, "mmd_uniform")) for a in arms), default=0)
        off = (s_vals.index(s) - (len(s_vals) - 1) / 2) * 0.12
        axA.errorbar([x + off for x in xs], ms, yerr=cs, fmt="o-",
                     color=S_COLORS.get(s, MUTED), markersize=5, capsize=3,
                     linewidth=1.5, label=f"s = {s:g} (n={n_pairs} pairs)")
        axB.plot(xs, [diag_ent.get((s, a), float("nan")) for a in arms], "o-",
                 color=S_COLORS.get(s, MUTED), markersize=5, linewidth=1.5)
    axA.axhline(0, color=INK, linewidth=1)
    axA.set_xticks(list(xs))
    axA.set_xticklabels([ARM_SHORT[a] for a in arms], fontsize=9)
    axA.set_ylabel("paired dist_uni diff vs uniform\n(negative = arm beats uniform)", fontsize=9)
    axA.set_title("A — does sharpening help?", fontsize=10)
    axA.legend(fontsize=8.5, frameon=False)
    if any(a == "mmd_uniform" for _, a in diag_ent):
        pass
    axB.axhline(1.0, color=MUTED, linewidth=1, linestyle="--")
    axB.text(0.02, 1.0, "uniform (H=1)", fontsize=8, color=MUTED, va="bottom")
    axB.set_xticks(list(xs))
    axB.set_xticklabels([ARM_SHORT[a] for a in arms], fontsize=9)
    axB.set_ylabel("normalized selection entropy H", fontsize=9)
    axB.set_title("B — does sharpening happen? (S1)", fontsize=10)
    for ax in (axA, axB):
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(axis="y", alpha=0.18)
    fig.suptitle("Round 4 — sharpened witness selection (marker = mean, bar = 95% CI; "
                 "top-k entropy is the ln k/ln n convention)", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig_path = os.path.join(_HERE, "figures", "fig5_sharpness.png")
    fig.savefig(fig_path, dpi=150)
    plt.close(fig)
    L.append(f"Figure: `figures/fig5_sharpness.png`")

    out = os.path.join(_HERE, "SHARPNESS.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out} and {fig_path}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
