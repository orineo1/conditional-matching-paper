"""
build_concentration_report.py — aggregate results/concentration_*.json into
CONCENTRATION.md (table: paired witness-uniform dist_uni diff per s, per seed
and pooled, plus the C2 selection diagnostics) and the money plot
figures/fig4_witness_vs_s.png (paired diff vs s with 95% CIs, pooled bold,
per-seed faint). Predictions C1-C3 in HYPOTHESIS.md "Round 3".
"""
import os, sys, glob, json, math
from collections import defaultdict

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std, median, t975

C_POOL, MUTED, INK = "#E69F00", "#8a8a8a", "#333333"


def paired(by, s, seeds, metric="dist_uni"):
    """Per-seed and pooled paired diff lists (witness - uniform) at this s."""
    per_seed, pooled = {}, []
    for seed in seeds:
        w = by.get((s, seed, "mmd_witness"), {})
        u = by.get((s, seed, "mmd_uniform"), {})
        d = [w[i][metric] - u[i][metric] for i in sorted(set(w) & set(u))]
        per_seed[seed] = d
        pooled += d
    return per_seed, pooled


def ci95(d):
    if len(d) < 2:
        return float("nan"), float("nan")
    m, sd = mean_std(d)
    return m, t975(len(d) - 1) * sd / math.sqrt(len(d))


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(_HERE, "results", "concentration_*.json")))
    if not paths:
        sys.exit("no concentration result JSONs found")
    by = defaultdict(dict)   # [(s, seed, arm)][restart] = row
    metas = []
    for p in paths:
        d = json.load(open(p))
        for r in d["rows"]:
            by[(r["s"], r["seed"], r["arm"])][r["restart"]] = r
        metas.append((os.path.basename(p), d["meta"]))
    s_vals = sorted({s for s, _, _ in by})
    seeds = sorted({sd for _, sd, _ in by})

    L = ["# Round 3 — witness advantage vs target concentration", "",
         "*Generated by build_concentration_report.py; predictions C1-C3 in "
         "HYPOTHESIS.md ('Round 3'). Bandwidth policy: fixed rounds-1-2 adaptive "
         "rule, never tuned per s. Metric: dist_uni = |x̂ − x_uni| (x-space; "
         "y-space metrics are basin-level, see IDENTIFIABILITY.md).*",
         "", "Input files:", ""]
    for name, meta in metas:
        L.append(f"- `{name}` — s_list={meta['s_list']}, arms={meta['arms']}, "
                 f"seeds={meta['seeds']}, n_restarts={meta['n_restarts']}")

    # C1 table
    L += ["", "## C1 — paired dist_uni diff (witness − uniform) vs s", "",
          "| s | " + " | ".join(f"seed {sd}" for sd in seeds) +
          " | pooled | n pooled pairs |",
          "|---|" + "---|" * (len(seeds) + 2)]
    fig_data = {}
    for s in s_vals:
        per_seed, pooled = paired(by, s, seeds)
        cells = []
        for sd in seeds:
            m, c = ci95(per_seed[sd])
            star = "*" if c == c and abs(m) > c else ""
            cells.append(f"{m:+.4f}{star} ±{c:.4f}" if per_seed[sd] else "—")
        m, c = ci95(pooled)
        star = "*" if c == c and abs(m) > c else ""
        cells.append(f"**{m:+.4f}{star} ±{c:.4f}**")
        L.append(f"| {s:g} | " + " | ".join(cells) + f" | {len(pooled)} |")
        fig_data[s] = (per_seed, pooled)
    L += ["", "`*` = 95% CI excludes 0. C1 predicts the pooled column grows more "
          "negative as s shrinks.", ""]

    # C2 table
    L += ["## C2 — selection diagnostics (mean over restarts of per-run means)", "",
          "| s | arm | frac_selected_offmode | frac_offmode (base rate) |",
          "|---|---|---|---|"]
    for s in s_vals:
        for arm in ("mmd_uniform", "mmd_witness"):
            rows = [r for sd in seeds for r in by.get((s, sd, arm), {}).values()
                    if r.get("frac_selected_offmode") == r.get("frac_selected_offmode")]
            if not rows:
                continue
            fs, _ = mean_std([r["frac_selected_offmode"] for r in rows])
            fo, _ = mean_std([r["frac_offmode"] for r in rows])
            L.append(f"| {s:g} | {arm} | {fs:.4f} | {fo:.4f} |")
    L += ["", "C2 predicts witness's frac_selected_offmode > its base rate "
          "(uniform's ≈ base rate), gap growing as s shrinks.", ""]

    # C3: full-mmd basin correctness
    L += ["## C3 — full-mmd reference basin correctness per s", ""]
    for s in s_vals:
        rows = [r for sd in seeds for r in by.get((s, sd, "mmd"), {}).values()]
        if rows:
            frac = sum(r["x_hat"] > 0 for r in rows) / len(rows)
            dm, _ = mean_std([r["dist_uni"] for r in rows])
            L.append(f"- s={s:g}: correct basin {frac:.2%} of {len(rows)} runs; "
                     f"mean dist_uni {dm:.3f}")
    L.append("")

    # money plot
    os.makedirs(os.path.join(_HERE, "figures"), exist_ok=True)
    fig, ax = plt.subplots(figsize=(6.8, 4.4))
    seed_styles = dict(zip(seeds, ["--", ":"]))
    for sd in seeds:
        n_sd = max(len(fig_data[s][0][sd]) for s in s_vals)
        ms, cs = zip(*[ci95(fig_data[s][0][sd]) for s in s_vals])
        ax.errorbar(s_vals, ms, yerr=cs, fmt="o" + seed_styles.get(sd, "--"),
                    color=MUTED, alpha=0.55, markersize=4, capsize=3,
                    linewidth=1, label=f"seed {sd} (n={n_sd})")
    n_pool = max(len(fig_data[s][1]) for s in s_vals)
    ms, cs = zip(*[ci95(fig_data[s][1]) for s in s_vals])
    ax.errorbar(s_vals, ms, yerr=cs, fmt="o-", color=C_POOL, markersize=7,
                capsize=5, linewidth=2, markeredgecolor="white",
                markeredgewidth=1, label=f"pooled (n={n_pool})", zorder=5)
    for s, m in zip(s_vals, ms):
        ax.annotate(f"{m:+.3f}", (s, m), xytext=(0, 9), textcoords="offset points",
                    ha="center", fontsize=8.5, color=INK)
    ax.axhline(0, color=INK, linewidth=1)
    ax.set_xscale("log")
    ax.set_xticks(s_vals)
    ax.set_xticklabels([f"{s:g}" for s in s_vals])
    ax.minorticks_off()
    ax.set_xlabel("unimodal target std s  (← more concentrated)", fontsize=10)
    ax.set_ylabel("paired diff per restart:\n"
                  r"dist$(\hat{x},x_{uni})_{witness}$ − dist$(\hat{x},x_{uni})_{uniform}$",
                  fontsize=9)
    ax.legend(fontsize=8.5, frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(axis="y", alpha=0.18)
    ax.set_title("Does the witness advantage grow with target concentration?\n"
                 "negative = witness lands closer to $x_{uni}$; marker = mean, bar = 95% CI",
                 fontsize=10)
    fig.tight_layout()
    fig_path = os.path.join(_HERE, "figures", "fig4_witness_vs_s.png")
    fig.savefig(fig_path, dpi=150)
    plt.close(fig)
    L.append(f"Money plot: `figures/fig4_witness_vs_s.png`")

    out = os.path.join(_HERE, "CONCENTRATION.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out} and {fig_path}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
