"""
build_identifiability_report.py — aggregate results/identifiability_*.json into
IDENTIFIABILITY.md: landing map per (seed, convention, target, arm), the
pre-registered mean-arm two-sample KS test (R1, per seed and pooled), and
paired witness-vs-uniform diffs (R3) per seed and POOLED across seeds (pairs
keyed by (seed, restart)). See HYPOTHESIS.md "Round 2" for predictions R1-R4.

Multiple seeds (e.g. the seed-42 primary array + the seed-1042 confirmation
array) are kept separate in the landing map and per-seed R3, and combined only
in the explicitly-labelled pooled rows.
"""
import os, sys, glob, json
from collections import defaultdict

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std, median, t975, paired_diff  # reuse round-1 helpers

R3_METRICS = ("dist_bi", "dist_uni", "mmd_to_bi", "mmd_to_uni", "gen_std", "frac_within_2s")


def r3_rows(L, by, keys, seed_label):
    for (conv, t, a) in keys:
        if a != "mmd_witness":
            continue
        ku = (conv, t, "mmd_uniform")
        if ku not in by:
            continue
        for m in R3_METRICS:
            pd = paired_diff(by[(conv, t, a)], by[ku], m)
            if pd:
                d, ci, n = pd
                med = median([by[(conv, t, a)][k][m] - by[ku][k][m]
                              for k in sorted(set(by[(conv, t, a)]) & set(by[ku]))])
                star = " *" if ci == ci and abs(d) > ci else ""
                L.append(f"| {seed_label} | {conv} | {t} | {m} | {d:+.4f}{star} | "
                         f"±{ci:.4f} | {med:+.4f} | {n} |")


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(_HERE, "results", "identifiability_*.json")))
    if not paths:
        sys.exit("no identifiability result JSONs found")
    metas = []
    by_pooled = defaultdict(dict)    # [(conv,t,a)][(seed,restart)] = row
    by_seed = defaultdict(dict)      # [(seed,conv,t,a)][restart] = row
    for p in paths:
        with open(p) as f:
            d = json.load(f)
        seed = d["meta"]["seed"]
        for r in d["rows"]:
            by_pooled[(r["convention"], r["target"], r["arm"])][(seed, r["restart"])] = r
            by_seed[(seed, r["convention"], r["target"], r["arm"])][r["restart"]] = r
        metas.append((os.path.basename(p), d["meta"]))
    seeds = sorted({s for s, _, _, _ in by_seed})

    L = ["# Round 2 — identifiability results", "",
         "*Generated by build_identifiability_report.py; predictions R1-R4 in "
         "HYPOTHESIS.md ('Round 2'). Seeds are separate arrays: the primary "
         "(42) and the pre-registered confirmation (1042); 'pooled' rows "
         "combine them with pairs keyed by (seed, restart).*",
         "", f"Input files ({len(metas)}):", ""]
    for name, meta in metas:
        L.append(f"- `{name}` — seed={meta['seed']}, conv={meta['convention']}, "
                 f"targets={meta['targets']}, arms={meta['arms']}, n_restarts={meta['n_restarts']}")

    L += ["", "## Landing map & cross-MMD (mean ± std [median])", "",
          "*Y-space eval columns (MMD→bi/uni, gen std, frac 2s) are BASIN-LEVEL "
          "only: evaluation is seed-paired per restart across arms/conventions, "
          "and p(y|x̂) is exactly locally constant deep in a basin (w_C saturates "
          "to float 0/1 beyond |x∓2|≈0.3; component means/stds are x-independent), "
          "so same-basin landings yield byte-identical eval samples by "
          "construction. Within-basin differences live in the x-space columns "
          "(|x−x_bi|, |x−x_uni|).*", "",
          "| seed | conv | target | arm | n | land@bi | land@uni | \\|x−x_bi\\| | \\|x−x_uni\\| "
          "| MMD→bi | MMD→uni | gen std | frac 2s |", "|" + "---|" * 13]
    for (seed, conv, t, a) in sorted(by_seed):
        rs = list(by_seed[(seed, conv, t, a)].values())
        n = len(rs)
        def ms(k):
            m, sd = mean_std([r[k] for r in rs]); return f"{m:.3f}±{sd:.3f} [{median([r[k] for r in rs]):.3f}]"
        land_bi = sum(r["land_bi"] for r in rs) / n
        land_uni = sum(r["land_uni"] for r in rs) / n
        L.append(f"| {seed} | {conv} | {t} | {a} | {n} | {land_bi:.2f} | {land_uni:.2f} | "
                 f"{ms('dist_bi')} | {ms('dist_uni')} | {ms('mmd_to_bi')} | "
                 f"{ms('mmd_to_uni')} | {ms('gen_std')} | {ms('frac_within_2s')} |")
    L.append("")

    # R1: KS between landing sets across targets, per seed and pooled
    L += ["## R1 — mean-arm landing degeneracy (two-sample KS, x_hat: bi-target vs uni-target)", ""]
    try:
        from scipy.stats import ks_2samp
        conv_arms = sorted({(c, a) for c, _, a in by_pooled})
        for conv, arm in conv_arms:
            kb, ku = (conv, "bi", arm), (conv, "uni", arm)
            if kb not in by_pooled or ku not in by_pooled:
                continue
            parts = []
            for seed in seeds:
                xb = [r["x_hat"] for r in by_seed.get((seed, conv, "bi", arm), {}).values()]
                xu = [r["x_hat"] for r in by_seed.get((seed, conv, "uni", arm), {}).values()]
                if xb and xu:
                    ks = ks_2samp(xb, xu)
                    parts.append(f"seed {seed}: KS={ks.statistic:.3f} p={ks.pvalue:.4f} (n={len(xb)},{len(xu)})")
            xb = [r["x_hat"] for r in by_pooled[kb].values()]
            xu = [r["x_hat"] for r in by_pooled[ku].values()]
            ks = ks_2samp(xb, xu)
            note = " <- R1 prediction: NOT significant" if arm == "mean" else ""
            L.append(f"- {conv} / **{arm}**: " + "; ".join(parts) +
                     f"; **pooled**: KS={ks.statistic:.3f} p={ks.pvalue:.4f} (n={len(xb)},{len(xu)}){note}")
    except ImportError:
        L.append("*(scipy unavailable — KS test skipped)*")
    L.append("")

    # R3: per-seed and pooled paired diffs
    L += ["## R3 — paired diffs: mmd_witness − mmd_uniform (per seed, then pooled)", "",
          "| seed | conv | target | metric | diff | 95% CI | median | n pairs |",
          "|---|---|---|---|---|---|---|---|"]
    for seed in seeds:
        keys = sorted({(c, t, a) for (s, c, t, a) in by_seed if s == seed})
        by_this = {(c, t, a): by_seed[(seed, c, t, a)] for (c, t, a) in keys}
        r3_rows(L, by_this, keys, str(seed))
    r3_rows(L, by_pooled, sorted(by_pooled), "pooled")
    L += ["", "`*` = 95% CI excludes 0. dist_bi/dist_uni (x-space) are the "
          "informative within-basin metrics; the y-space rows (mmd_to_*, gen_std, "
          "frac_within_2s) are structurally zero whenever both arms land in the "
          "same basin on every restart (see basin-level note above).", ""]

    out = os.path.join(_HERE, "IDENTIFIABILITY.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
