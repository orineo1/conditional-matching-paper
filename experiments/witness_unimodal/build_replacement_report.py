"""
build_replacement_report.py — Round 5: with- vs without-replacement witness
sampling. Reads BOTH results/replacement_*.json (round-5 wor arms) and
results/sharpness_*cell*.json (round-4 with-replacement arms, reused — same
seeds/restarts) and writes REPLACEMENT.md + figures/fig7_replacement.png:

  - paired diff vs the MATCHING-MODE uniform reference per (s, beta, mode)
  - the direct with-vs-without paired contrast at each beta (and for uniform)
  - expected duplicate share of the k budget for the round-4 arms, computed
    analytically from their logged selection entropy (perplexity estimate,
    documented — duplicate rates were not recorded in round 4).

Prediction R5 in HYPOTHESIS.md "Round 5".
"""
import os, sys, glob, json, math
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std, t975

BETAS = [1.0, 2.0, 4.0]
WR = {1.0: "witness_b1_f0", 2.0: "witness_b2_f0", 4.0: "witness_b4_f0"}
WOR = {1.0: "witness_b1_wor", 2.0: "witness_b2_wor", 4.0: "witness_b4_wor"}
UREF = {"wr": "mmd_uniform", "wor": "uniform_wor"}
S_COLORS = {0.25: "#E69F00", 0.50: "#009E73"}
INK, MUTED = "#333333", "#8a8a8a"
N, K = 32, 8


def ci95(d):
    if len(d) < 2:
        return float("nan"), float("nan")
    m, sd = mean_std(d)
    return m, t975(len(d) - 1) * sd / math.sqrt(len(d))


def pair(by, s, arm_a, arm_b, metric="dist_uni"):
    a, b = by.get((s, arm_a), {}), by.get((s, arm_b), {})
    ks = sorted(set(a) & set(b))
    return [a[k][metric] - b[k][metric] for k in ks]


def fmt(d):
    m, c = ci95(d)
    if m != m:
        return "—", (float("nan"), float("nan"))
    star = "*" if c == c and abs(m) > c else ""
    return f"{m:+.4f}{star} ±{c:.4f}", (m, c)


def main():
    paths = (sorted(glob.glob(os.path.join(_HERE, "results", "replacement_*.json")))
             + sorted(glob.glob(os.path.join(_HERE, "results", "sharpness_*cell*.json"))))
    if not paths:
        sys.exit("no result JSONs found")
    by = defaultdict(dict)   # [(s, arm)][(seed, restart)] = row
    metas = []
    for p in paths:
        d = json.load(open(p))
        for r in d["rows"]:
            by[(r["s"], r["arm"])][(r["seed"], r["restart"])] = r
        metas.append((os.path.basename(p), d["meta"]))
    s_vals = sorted({s for s, _ in by if (s, "witness_b4_wor") in by or (s, "uniform_wor") in by})
    if not s_vals:
        s_vals = sorted({s for s, _ in by})

    L = ["# Round 5 — with- vs without-replacement witness sampling", "",
         "*Generated by build_replacement_report.py; prediction R5 in "
         "HYPOTHESIS.md ('Round 5'). WITH-replacement rows are round-4 results "
         "reused (same seeds/restarts). Without-replacement witness arms use the "
         "documented approximate HT weights (pi ≈ 1−(1−p)^k); uniform_wor is "
         "exactly unbiased (n/k). Metric: dist_uni.*", "",
         f"Input files ({len(metas)}).", ""]

    # per-mode diff vs matching uniform
    L += ["## Paired diff vs the MATCHING-MODE uniform reference", "",
          "| s | β | with-repl (round 4) | without-repl (round 5) |",
          "|---|---|---|---|"]
    fig_a = {}
    for s in s_vals:
        for b in BETAS:
            cw, vw = fmt(pair(by, s, WR[b], UREF["wr"]))
            co, vo = fmt(pair(by, s, WOR[b], UREF["wor"]))
            fig_a[(s, b, "wr")], fig_a[(s, b, "wor")] = vw, vo
            L.append(f"| {s:g} | {b:g} | {cw} | {co} |")

    # direct paired contrast wor - wr
    L += ["", "## Direct paired contrast: without − with (same β, same (seed, restart))", "",
          "*R5 predicts ≤ 0 at β=4, ≈ 0 at β=1. Also shown: the two uniform "
          "references against each other (both exactly unbiased; differ only in "
          "duplicate noise).*", "",
          "| s | contrast | diff (95% CI) |", "|---|---|---|"]
    fig_b = {}
    for s in s_vals:
        for b in BETAS:
            c, v = fmt(pair(by, s, WOR[b], WR[b]))
            fig_b[(s, b)] = v
            L.append(f"| {s:g} | β={b:g}: wor − wr | {c} |")
        c, v = fmt(pair(by, s, "uniform_wor", "mmd_uniform"))
        L.append(f"| {s:g} | uniform: wor − wr | {c} |")

    # analytic duplicate share from round-4 entropies
    L += ["", "## Expected duplicate share of the k=8 budget (round-4 with-replacement arms)", "",
          "*Analytic perplexity estimate from logged selection entropy H "
          "(m = n^H effective categories; E[#distinct] = m(1−(1−1/m)^k); "
          "share = 1 − E[#distinct]/k). Round 4 did not record actual duplicate "
          "counts — this is an estimate, documented as such.*", "",
          "| s | arm | mean H | m = n^H | expected duplicate share |",
          "|---|---|---|---|---|"]
    for s in s_vals:
        for b in BETAS:
            rows = list(by.get((s, WR[b]), {}).values())
            hs = [r["sel_entropy"] for r in rows if "sel_entropy" in r]
            if not hs:
                continue
            H = sum(hs) / len(hs)
            m = N ** H
            e_dist = m * (1.0 - (1.0 - 1.0 / m) ** K)
            L.append(f"| {s:g} | β={b:g} wr | {H:.3f} | {m:.1f} | {1 - e_dist / K:.1%} |")
    L.append("")

    # figure
    os.makedirs(os.path.join(_HERE, "figures"), exist_ok=True)
    fig, (axA, axB) = plt.subplots(1, 2, figsize=(9.6, 4.2))
    for s in s_vals:
        for mode, ls, mk in (("wr", "--", "o"), ("wor", "-", "s")):
            ms = [fig_a.get((s, b, mode), (float("nan"),) * 2)[0] for b in BETAS]
            cs = [fig_a.get((s, b, mode), (float("nan"),) * 2)[1] for b in BETAS]
            axA.errorbar(BETAS, ms, yerr=cs, fmt=mk + ls, color=S_COLORS.get(s, MUTED),
                         markersize=5, capsize=3, linewidth=1.5,
                         label=f"s={s:g}, {'with' if mode == 'wr' else 'without'} repl.")
        ms = [fig_b.get((s, b), (float("nan"),) * 2)[0] for b in BETAS]
        cs = [fig_b.get((s, b), (float("nan"),) * 2)[1] for b in BETAS]
        axB.errorbar(BETAS, ms, yerr=cs, fmt="o-", color=S_COLORS.get(s, MUTED),
                     markersize=6, capsize=4, linewidth=1.8, label=f"s = {s:g}")
    for ax, ttl, yl in ((axA, "A — paired diff vs matching-mode uniform",
                         "dist_uni diff vs uniform\n(negative = witness beats uniform)"),
                        (axB, "B — direct contrast: without − with (paired)",
                         "dist_uni diff, wor − wr\n(negative = without-replacement better)")):
        ax.axhline(0, color=INK, linewidth=1)
        ax.set_xscale("log", base=2)
        ax.set_xticks(BETAS)
        ax.set_xticklabels([f"β={b:g}" for b in BETAS])
        ax.minorticks_off()
        ax.set_ylabel(yl, fontsize=9)
        ax.set_title(ttl, fontsize=10)
        ax.legend(fontsize=8, frameon=False)
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(axis="y", alpha=0.18)
    fig.suptitle("Round 5 — replacement mode (marker = mean, bar = 95% CI; "
                 "with-replacement rows reuse round-4 runs)", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig_path = os.path.join(_HERE, "figures", "fig7_replacement.png")
    fig.savefig(fig_path, dpi=150)
    plt.close(fig)
    L.append("Figure: `figures/fig7_replacement.png`")

    out = os.path.join(_HERE, "REPLACEMENT.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out} and {fig_path}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
