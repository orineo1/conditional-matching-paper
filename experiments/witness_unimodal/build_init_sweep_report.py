"""
build_init_sweep_report.py — Round 7: init sweep. Reads results/initsweep_*.json
and writes INIT_SWEEP.md + figures/fig9_init_sweep.png:
  panel A — fraction landing in the uni basin (x_hat > 0) vs init offset c,
            one curve per arm (the capture-window / objective-pull picture);
  panel B — mean distance to the CORRECT design point vs c for the two MMD
            arms, with 95% CIs (the distributional-robustness readout).
Predictions (i)-(iii) in HYPOTHESIS.md "Round 7".
"""
import os, sys, glob, json, math
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std, t975

X_BI, X_UNI = -2.0, 2.0
ARM_ORDER = ["point_sq_a0", "point_sq_a2", "point_abs_a2", "mmd_bi", "mmd_uni"]
ARM_LABEL = {"point_sq_a0": "pointwise (y−0)²", "point_sq_a2": "pointwise (y−2)²",
             "point_abs_a2": "pointwise |y−2|",
             "mmd_bi": "MMD (bimodal target)", "mmd_uni": "MMD (unimodal target)"}
C_ARM = {"point_sq_a0": "#0072B2", "point_sq_a2": "#E69F00", "point_abs_a2": "#CC79A7",
         "mmd_bi": "#333333", "mmd_uni": "#8a8a8a"}
MK_ARM = {"point_sq_a0": "o", "point_sq_a2": "s", "point_abs_a2": "^",
          "mmd_bi": "D", "mmd_uni": "v"}
CORRECT_DIST = {"mmd_bi": "dist_bi", "mmd_uni": "dist_uni"}
INK, MUTED = "#333333", "#8a8a8a"


def ci95(vals):
    if len(vals) < 2:
        return float("nan"), float("nan")
    m, sd = mean_std(vals)
    return m, t975(len(vals) - 1) * sd / math.sqrt(len(vals))


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(_HERE, "results", "initsweep_*.json")))
    if not paths:
        sys.exit("no initsweep result JSONs found")
    by = defaultdict(dict)   # [(arm, c)][(seed, restart)] = row
    metas = []
    for p in paths:
        d = json.load(open(p))
        for r in d["rows"]:
            by[(r["arm"], r["init_offset"])][(r["seed"], r["restart"])] = r
        metas.append((os.path.basename(p), d["meta"]))
    c_vals = sorted({c for _, c in by})
    arms = [a for a in ARM_ORDER if any(a == arm for arm, _ in by)]

    L = ["# Round 7 — init sweep: objective pull vs basin capture", "",
         "*Generated by build_init_sweep_report.py; predictions (i)-(iii) in "
         "HYPOTHESIS.md ('Round 7'). x_T ~ c + N(0,1); x_bi = −2, x_uni = +2. "
         "MMD reference arms re-run at each offset (round-2 rows unusable — "
         "init changed).*", "", f"Input files ({len(metas)}).", "",
         "## Fraction landing in the uni basin (x̂ > 0) vs init offset c", "",
         "| arm | " + " | ".join(f"c={c:+g}" for c in c_vals) + " |",
         "|---|" + "---|" * len(c_vals)]
    frac_uni = {}
    for a in arms:
        cells = []
        for c in c_vals:
            rows = list(by.get((a, c), {}).values())
            if rows:
                f = sum(r["x_hat"] > 0 for r in rows) / len(rows)
                frac_uni[(a, c)] = f
                cells.append(f"{f:.2f} (n={len(rows)})")
            else:
                cells.append("—")
        L.append(f"| {ARM_LABEL.get(a, a)} | " + " | ".join(cells) + " |")

    L += ["", "## MMD arms — mean distance to the CORRECT design point vs c (95% CI)", "",
          "| arm | " + " | ".join(f"c={c:+g}" for c in c_vals) + " |",
          "|---|" + "---|" * len(c_vals)]
    mmd_dist = {}
    for a in ("mmd_bi", "mmd_uni"):
        if a not in arms:
            continue
        cells = []
        for c in c_vals:
            rows = list(by.get((a, c), {}).values())
            if rows:
                m, ci = ci95([r[CORRECT_DIST[a]] for r in rows])
                mmd_dist[(a, c)] = (m, ci)
                cells.append(f"{m:.3f} ±{ci:.3f}")
            else:
                cells.append("—")
        L.append(f"| {ARM_LABEL[a]} | " + " | ".join(cells) + " |")
    L += ["", "Prediction (iii): mmd_bi should stay near-0 dist even at c=+3 "
          "(and mmd_uni at c=−3); a rise at extreme wrong-side c is the capture "
          "radius, reported as found.", ""]

    # figure
    os.makedirs(os.path.join(_HERE, "figures"), exist_ok=True)
    fig, (axA, axB) = plt.subplots(1, 2, figsize=(9.8, 4.2))
    for a in arms:
        fs = [frac_uni.get((a, c), float("nan")) for c in c_vals]
        axA.plot(c_vals, fs, MK_ARM.get(a, "o") + "-", color=C_ARM.get(a, MUTED),
                 markersize=5, linewidth=1.6, label=ARM_LABEL.get(a, a))
    axA.axhline(0.5, color=MUTED, linewidth=0.8, linestyle=":")
    for xd in (X_BI, X_UNI):
        axA.axvline(xd, color=MUTED, linestyle="--", linewidth=0.8)
    axA.set_ylim(-0.04, 1.04)
    axA.set_xlabel("init offset c   (x_T ~ c + N(0,1))", fontsize=9.5)
    axA.set_ylabel("fraction landing in uni basin (x̂ > 0)", fontsize=9.5)
    axA.set_title("A — landings vs init (capture window)", fontsize=10)
    axA.legend(fontsize=8, frameon=False, loc="best")
    for a in ("mmd_bi", "mmd_uni"):
        if a not in arms:
            continue
        ms = [mmd_dist.get((a, c), (float("nan"),) * 2)[0] for c in c_vals]
        cs = [mmd_dist.get((a, c), (float("nan"),) * 2)[1] for c in c_vals]
        axB.errorbar(c_vals, ms, yerr=cs, fmt=MK_ARM[a] + "-", color=C_ARM[a],
                     markersize=6, capsize=4, linewidth=1.8, label=ARM_LABEL[a])
    axB.set_xlabel("init offset c", fontsize=9.5)
    axB.set_ylabel("mean distance to CORRECT design point", fontsize=9.5)
    axB.set_title("B — MMD robustness to wrong-side inits", fontsize=10)
    axB.legend(fontsize=8, frameon=False)
    for ax in (axA, axB):
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(alpha=0.18)
        ax.set_xticks(c_vals)
    fig.suptitle("Round 7 — init sweep (both seeds pooled, 80 runs per point; "
                 "dashed verticals = design points)", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig_path = os.path.join(_HERE, "figures", "fig9_init_sweep.png")
    fig.savefig(fig_path, dpi=150)
    plt.close(fig)
    L.append("Figure: `figures/fig9_init_sweep.png`")

    out = os.path.join(_HERE, "INIT_SWEEP.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out} and {fig_path}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
