"""
analyze_sd.py — arm x seed table + paired-by-seed differences vs the control arm
for the SD perf campaign (output/sd_perf/<arm>_seed<s>/{metrics,profile}.json).

Usage: python experiments/model-optimization/sd/analyze_sd.py [--root output/sd_perf]
       [--control novis] [--out experiments/model-optimization/sd/RESULTS.md] [--boot 10000]
"""
import argparse
import glob
import json
import os
import re

import numpy as np

_RE = re.compile(r"^(?P<arm>.+)_seed(?P<seed>\d+)$")


def load_runs(root):
    runs = {}
    for d in sorted(glob.glob(os.path.join(root, "*_seed*"))):
        m = _RE.match(os.path.basename(d))
        mf, pf = os.path.join(d, "metrics.json"), os.path.join(d, "profile.json")
        if not m or not os.path.exists(mf):
            continue
        met = json.load(open(mf))
        prof = json.load(open(pf)) if os.path.exists(pf) else None
        steps = met.get("steps") or []
        secs = prof["summary"]["mean_sections_s"] if prof else {}
        a = met["args"]
        n_var = a["num_variations"]
        k = a.get("backsel", 0) or 0
        n_diff = min(k, n_var) if k else n_var
        r = {
            "arm": m["arm"], "seed": int(m["seed"]),
            "mmd": met["final_mlgd_f_mmd"], "unguided": met["final_regular_mmd"],
            "delta": met["final_regular_mmd"] - met["final_mlgd_f_mmd"],
            "s_step": prof["summary"]["mean_total_s"] if prof else float("nan"),
            "backward_s": secs.get("backward", float("nan")),
            "fwd_s": sum(v for kk, v in secs.items() if kk.startswith(("sprinter_fwd", "nograd_", "vae", "clip"))),
            "vram_gb": (prof["summary"]["max_memory_allocated_mb"] / 1024) if prof else float("nan"),
            "forwards": n_var + (n_diff if k else 0), "diff_vars": n_diff,
            "n_capped": sum(1 for s in steps if s.get("trust_scale", 1.0) < 1.0),
            "n_steps": len(steps), "half_split": met.get("eval_half_split_mmd"),
            "sections": secs,
        }
        runs.setdefault(m["arm"], {})[int(m["seed"])] = r
    return runs


def bootstrap_ci(x, B, rng):
    x = np.asarray(x, float)
    if len(x) < 2:
        return (float("nan"), float("nan"))
    idx = rng.integers(0, len(x), size=(B, len(x)))
    means = x[idx].mean(axis=1)
    return (float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="output/sd_perf")
    ap.add_argument("--control", default="novis")
    ap.add_argument("--out", default="experiments/model-optimization/sd/RESULTS.md")
    ap.add_argument("--boot", type=int, default=10000)
    args = ap.parse_args()
    runs = load_runs(args.root)
    rng = np.random.default_rng(0)
    L = ["# SD perf campaign — results (auto-generated by analyze_sd.py)", "",
         f"Root `{args.root}`, control arm `{args.control}`. Final MMD = 2000 fresh sprinter photos vs the "
         "cached 50/50 targets (CLIP MMD, sqrt, unbiased); delta = unguided - guided (higher = more guidance effect).",
         "", "## Arm x seed", "",
         "| arm | seed | final MMD | unguided | delta | s/step | backward s | fwd s | VRAM GB | forwards | diff. vars | steps capped |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in sorted(runs):
        for seed in sorted(runs[arm]):
            r = runs[arm][seed]
            L.append(f"| {arm} | {seed} | {r['mmd']:.4f} | {r['unguided']:.4f} | {r['delta']:+.4f} | {r['s_step']:.1f} | "
                     f"{r['backward_s']:.1f} | {r['fwd_s']:.1f} | {r['vram_gb']:.1f} | {r['forwards']} | {r['diff_vars']} | {r['n_capped']}/{r['n_steps']} |")
    L += ["", "## Per-arm means", "", "| arm | n seeds | mean MMD | sd | mean s/step | mean VRAM GB |", "|---|---|---|---|---|---|"]
    for arm in sorted(runs):
        v = [r["mmd"] for r in runs[arm].values()]
        L.append(f"| {arm} | {len(v)} | {np.mean(v):.4f} | {np.std(v, ddof=1) if len(v) > 1 else float('nan'):.4f} | "
                 f"{np.nanmean([r['s_step'] for r in runs[arm].values()]):.1f} | {np.nanmean([r['vram_gb'] for r in runs[arm].values()]):.1f} |")
    ctrl = runs.get(args.control, {})
    L += ["", f"## Paired-by-seed differences vs `{args.control}` (arm MMD - control MMD; negative = arm better)", "",
          "Bootstrap 95% CI of the mean paired difference over seeds (percentile, 10k resamples). "
          "With <= 4 seeds the CI is wide and the resample distribution has few support points — treat as "
          "indicative only; the single-run noise floor (two runs of an identical computation) was ~0.05 on seed 1.", "",
          "| arm | paired seeds | diffs | mean diff | 95% CI | speedup (s/step ctrl / arm) |", "|---|---|---|---|---|---|"]
    for arm in sorted(runs):
        if arm == args.control:
            continue
        seeds = sorted(set(runs[arm]) & set(ctrl))
        if not seeds:
            L.append(f"| {arm} | 0 | — | — | — | — |")
            continue
        diffs = [runs[arm][s]["mmd"] - ctrl[s]["mmd"] for s in seeds]
        lo, hi = bootstrap_ci(diffs, args.boot, rng)
        sp = np.nanmean([ctrl[s]["s_step"] for s in seeds]) / np.nanmean([runs[arm][s]["s_step"] for s in seeds])
        L.append(f"| {arm} | {len(seeds)} | {', '.join(f'{d:+.3f}' for d in diffs)} | {np.mean(diffs):+.4f} | "
                 f"[{lo:+.3f}, {hi:+.3f}] | {sp:.2f}x |")
    L += ["", "## Per-section mean seconds per step (first seed of each arm)", ""]
    keys = sorted({k for arm in runs for r in runs[arm].values() for k in r["sections"]})
    L.append("| arm | " + " | ".join(keys) + " |")
    L.append("|---|" + "---|" * len(keys))
    for arm in sorted(runs):
        r = runs[arm][min(runs[arm])]
        L.append(f"| {arm} | " + " | ".join(f"{r['sections'].get(k, 0):.2f}" for k in keys) + " |")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
