"""LM-on-LM conditional distribution matching with an EXACT oracle.

Task: find a framing x (a short preamble, generated by a masked diffusion LM)
such that a responder LM's answer distribution on a fixed multiple-choice
survey question matches a target population distribution G.

Why this task exists. In the image pipeline p(y|x) is only accessible through
Monte Carlo (sample images, CLIP-embed, biased MMD), so every loss value
carries estimator noise and there is a finite-sample floor. Here the
responder's answer is restricted to a small fixed option set, so

    p(y = option_j | x) = softmax(logits at the answer position)[j],
    renormalised over the option tokens,

is available EXACTLY from one forward pass. Consequences:
  * the optimum is a true zero, not a finite-sample floor;
  * L(x) is deterministic, so the only remaining stochasticity in guided
    sampling is the TWIST estimate itself -- which is exactly the mechanism
    the CTMC-vs-SMC comparison is about;
  * an eval costs milliseconds, so the whole prompt space can be enumerated
    by brute force at small vocabulary and every method scored against the
    true optimum rather than against the best value anyone happened to find.

The controlled vocabulary (--vocab_words / --vocab) makes |V| the single free
variable for the V-ladder: the framing words are nominally about *how* the
question is asked, never about the answer itself, so the answer distribution
stays underdetermined by construction.
"""

