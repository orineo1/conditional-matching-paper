"""
build_report.py — aggregate results/*.json from exp_witness_unimodal.py into
RESULTS.md with per-(target, arm) means and PAIRED (same restart index) diffs
with 95% t-CIs for the pre-registered contrasts:

  - mmd vs mean          (P1-P3: mean-blindness / concentration failure)
  - mmd_witness vs mmd_uniform  (P4: witness helps, most at small s)

Usage:
    python build_report.py                     # all results/*.json
    python build_report.py results/foo.json    # specific file(s)
"""

import os
import sys
import glob
import json
import math
from collections import defaultdict

_HERE = os.path.dirname(os.path.abspath(__file__))

METRICS = ["final_mmd", "abs_mean_err", "gen_std", "frac_within_2s"]

# two-sided 97.5% t quantiles by df (fallback: 1.96); avoids a scipy dependency
_T975 = {1: 12.71, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365,
         8: 2.306, 9: 2.262, 10: 2.228, 14: 2.145, 19: 2.093, 24: 2.064,
         29: 2.045, 39: 2.023, 49: 2.010, 59: 2.001, 99: 1.984}


def t975(df):
    if df <= 0:
        return float("nan")
    for k in sorted(_T975):
        if df <= k:
            return _T975[k]
    return 1.96


def median(vals):
    v = sorted(vals)
    n = len(v)
    return v[n // 2] if n % 2 else 0.5 * (v[n // 2 - 1] + v[n // 2])


def mean_std(vals):
    n = len(vals)
    m = sum(vals) / n
    sd = math.sqrt(sum((v - m) ** 2 for v in vals) / (n - 1)) if n > 1 else 0.0
    return m, sd


def paired_diff(rows_a, rows_b, metric):
    """rows keyed by restart; returns (mean_diff a-b, ci_half, n)."""
    common = sorted(set(rows_a) & set(rows_b))
    diffs = [rows_a[i][metric] - rows_b[i][metric] for i in common]
    if not diffs:
        return None
    m, sd = mean_std(diffs)
    n = len(diffs)
    ci = t975(n - 1) * sd / math.sqrt(n) if n > 1 else float("nan")
    return m, ci, n


def main():
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(_HERE, "results", "*.json")))
    if not paths:
        sys.exit("no result JSONs found — run exp_witness_unimodal.py first")

    rows, metas = [], []
    for p in paths:
        with open(p) as f:
            d = json.load(f)
        tau = d["meta"].get("step_cap_tau")
        regime = "nocap" if tau is None else f"cap{tau:g}"
        for r in d["rows"]:
            r["_regime"] = regime
        rows.extend(d["rows"])
        metas.append((os.path.basename(p), d["meta"]))

    # by[(regime|target, arm)] = {restart: row} (later files override same restart);
    # the step-cap regime is folded into the target label so round-1 (nocap) and
    # round-2 (capN) runs never mix or override each other.
    regimes = {r["_regime"] for r in rows}
    multi_regime = len(regimes) > 1
    by = defaultdict(dict)
    for r in rows:
        label = f"{r['_regime']}|{r['target']}" if multi_regime else r["target"]
        by[(label, r["arm"])][r["restart"]] = r
    targets = sorted({t for t, _ in by})
    arms = [a for a in ["mean", "mmd", "mmd_uniform", "mmd_witness"]
            if any(a == arm for _, arm in by)]

    lines = ["# Results — witness back-selection on unimodal vs bimodal targets", "",
             "*Auto-generated by build_report.py; see HYPOTHESIS.md for the "
             "pre-registered predictions P1-P4.*", "", "Input files:", ""]
    for name, meta in metas:
        lines.append(f"- `{name}` — targets={meta['targets']}, arms={meta['arms']}, "
                     f"n_restarts={meta['n_restarts']}, n={meta['nsamples']}, "
                     f"k={meta['backsel_k']}, num_x_t={meta['num_x_t']}, "
                     f"n_eval={meta['n_eval']}, seed={meta['seed']}, "
                     f"step_cap_tau={meta.get('step_cap_tau')}")
    lines.append("")

    # ── per-(target, arm) table ────────────────────────────────────────────
    lines += ["## Per-arm summary (mean ± std [median] over restarts)", "",
              "*Occasional restarts diverge (x drifts off-manifold; the raw "
              "optimize_LGD loop has no step cap by design, while the mean arm "
              "is norm-clipped for stability — see README deviation 3), so "
              "means are heavy-tailed; medians shown alongside.*", "",
              "| target | arm | n | final MMD | \\|mean err\\| | gen std | frac within 2s | time (s) |",
              "|---|---|---|---|---|---|---|---|"]
    for t in targets:
        for a in arms:
            if (t, a) not in by:
                continue
            rs = list(by[(t, a)].values())
            cells = []
            for m in METRICS + ["time_s"]:
                vals = [r[m] for r in rs]
                mu, sd = mean_std(vals)
                cells.append(f"{mu:.4f} ± {sd:.4f} [{median(vals):.4f}]")
            lines.append(f"| {t} | {a} | {len(rs)} | " + " | ".join(cells) + " |")
    lines.append("")

    # ── paired contrasts ───────────────────────────────────────────────────
    for title, a, b, note in [
        ("mmd − mean (negative MMD diff = MMD guidance beats mean guidance)",
         "mmd", "mean",
         "P1: |mean err| diff ≈ 0 or positive (mean arm aces its own metric). "
         "P2/P3: final_mmd and concentration should favor mmd, especially on unimodal targets."),
        ("mmd_witness − mmd_uniform (negative MMD diff = witness helped)",
         "mmd_witness", "mmd_uniform",
         "P4: most negative at the smallest s (unimodal_s010), shrinking with s and on bimodal."),
    ]:
        lines += [f"## Paired diffs: {title}", "", f"*{note}*", "",
                  "| target | metric | diff (a−b) | 95% CI | median diff | n pairs |", "|---|---|---|---|---|---|"]
        for t in targets:
            if (t, a) not in by or (t, b) not in by:
                continue
            for m in METRICS:
                pd = paired_diff(by[(t, a)], by[(t, b)], m)
                if pd is None:
                    continue
                d, ci, n = pd
                med = median([by[(t, a)][i][m] - by[(t, b)][i][m]
                              for i in sorted(set(by[(t, a)]) & set(by[(t, b)]))])
                star = " *" if not math.isnan(ci) and abs(d) > ci else ""
                lines.append(f"| {t} | {m} | {d:+.4f}{star} | ±{ci:.4f} | {med:+.4f} | {n} |")
        lines += ["", "`*` = 95% CI excludes 0.", ""]

    out = os.path.join(_HERE, "RESULTS.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
