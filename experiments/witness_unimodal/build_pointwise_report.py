"""
build_pointwise_report.py — Round 6: pointwise scalar-target baseline.
Reads results/pointwise_*.json (round-6 arms) plus the round-2 identifiability
mmd cells (results/identifiability_*_cap1_inv_cell_*_mmd.json, reused — no
rerun) and writes POINTWISE.md + figures/fig8_pointwise.png (landing-map strips
per arm, mmd reference rows included for contrast). Competing pre-registered
predictions P-a / P-b in HYPOTHESIS.md "Round 6" — the report states which
outcome the data supports.
"""
import os, sys, glob, json, math
from collections import defaultdict

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

_HERE = os.path.dirname(os.path.abspath(__file__))
from build_report import mean_std

X_BI, X_UNI = -2.0, 2.0
ARM_ORDER = ["point_sq_a0", "point_sq_a2", "point_abs_a2", "mmd|target=bi", "mmd|target=uni"]
ARM_LABEL = {"point_sq_a0": "pointwise (y−0)², n=1", "point_sq_a2": "pointwise (y−2)², n=1",
             "point_abs_a2": "pointwise |y−2|, n=1",
             "mmd|target=bi": "MMD, bimodal target set (round 2)",
             "mmd|target=uni": "MMD, unimodal target set (round 2)"}
C_ARM = {"point_sq_a0": "#0072B2", "point_sq_a2": "#E69F00", "point_abs_a2": "#CC79A7",
         "mmd|target=bi": "#8a8a8a", "mmd|target=uni": "#8a8a8a"}
INK, MUTED = "#333333", "#8a8a8a"


def main():
    by = defaultdict(dict)   # by[arm][(seed, restart)] = row
    metas = []
    for p in sorted(glob.glob(os.path.join(_HERE, "results", "pointwise_*.json"))):
        d = json.load(open(p))
        for r in d["rows"]:
            by[r["arm"]][(r["seed"], r["restart"])] = r
        metas.append((os.path.basename(p), d["meta"]))
    if not by:
        sys.exit("no pointwise result JSONs found")
    # reused round-2 mmd references
    for p in sorted(glob.glob(os.path.join(_HERE, "results", "identifiability_*_cap1_inv_cell_*_mmd.json"))):
        d = json.load(open(p))
        seed = d["meta"]["seed"]
        for r in d["rows"]:
            by[f"mmd|target={r['target']}"][(seed, r["restart"])] = r
    arms = [a for a in ARM_ORDER if a in by]

    L = ["# Round 6 — pointwise scalar-target baseline", "",
         "*Generated by build_pointwise_report.py; competing pre-registered "
         "predictions P-a (target-blind splitting) vs P-b (variance seeking) in "
         "HYPOTHESIS.md ('Round 6'). mmd rows are round-2 results reused. "
         "Either outcome supports the paper claim that a scalar target does not "
         "determine the answer.*", "", "Input files:", ""]
    for name, meta in metas:
        L.append(f"- `{name}` — arms={meta['arms']}, seeds={meta['seeds']}, "
                 f"n_restarts={meta['n_restarts']}")

    L += ["", "## Landing map", "",
          "| arm | n | frac basin bi (x̂<0) | frac basin uni (x̂>0) | mean \\|x̂\\| | "
          "mean \\|x̂−x_bi\\| | mean \\|x̂−x_uni\\| | MMD→bi | MMD→uni |",
          "|---|---|---|---|---|---|---|---|---|"]
    for a in arms:
        rs = list(by[a].values())
        n = len(rs)
        fb = sum(r["x_hat"] < 0 for r in rs) / n
        def mv(k):
            m, _ = mean_std([r[k] for r in rs]); return m
        L.append(f"| {ARM_LABEL.get(a, a)} | {n} | {fb:.2f} | {1 - fb:.2f} | "
                 f"{mv('x_hat') if False else sum(abs(r['x_hat']) for r in rs)/n:.3f} | "
                 f"{mv('dist_bi'):.3f} | {mv('dist_uni'):.3f} | "
                 f"{mv('mmd_to_bi'):.3f} | {mv('mmd_to_uni'):.3f} |")

    # KS: a0 vs a2 landing sets (P-b predicts identical)
    L += ["", "## KS — point_sq_a0 vs point_sq_a2 landing sets (identical under P-b)", ""]
    try:
        from scipy.stats import ks_2samp
        if "point_sq_a0" in by and "point_sq_a2" in by:
            seeds = sorted({s for s, _ in by["point_sq_a0"]})
            parts = []
            for sd in seeds:
                x0 = [r["x_hat"] for (s, _), r in by["point_sq_a0"].items() if s == sd]
                x2 = [r["x_hat"] for (s, _), r in by["point_sq_a2"].items() if s == sd]
                if x0 and x2:
                    ks = ks_2samp(x0, x2)
                    parts.append(f"seed {sd}: KS={ks.statistic:.3f} p={ks.pvalue:.4f}")
            x0 = [r["x_hat"] for r in by["point_sq_a0"].values()]
            x2 = [r["x_hat"] for r in by["point_sq_a2"].values()]
            ks = ks_2samp(x0, x2)
            L.append("- " + "; ".join(parts) +
                     f"; **pooled**: KS={ks.statistic:.3f} p={ks.pvalue:.4f} (n={len(x0)},{len(x2)})")
    except ImportError:
        L.append("*(scipy unavailable — KS skipped)*")
    L.append("")

    # figure: landing strips
    os.makedirs(os.path.join(_HERE, "figures"), exist_ok=True)
    rng = np.random.default_rng(0)
    fig, ax = plt.subplots(figsize=(8.4, 0.85 * len(arms) + 1.6))
    for row, a in enumerate(arms):
        v = np.array([r["x_hat"] for r in by[a].values()])
        y0 = len(arms) - 1 - row
        ax.scatter(v, y0 + rng.uniform(-0.18, 0.18, len(v)), s=13,
                   color=C_ARM.get(a, MUTED), alpha=0.55, linewidths=0, zorder=3)
        fb = (v < 0).mean()
        ax.text(1.01, y0, f"{ARM_LABEL.get(a, a)}\n{fb:.0%} bi / {1 - fb:.0%} uni (n={len(v)})",
                transform=ax.get_yaxis_transform(), fontsize=8.5, va="center", color=INK)
    for xd, lab in ((X_BI, "$x_{bi}=-2$"), (X_UNI, "$x_{uni}=+2$")):
        ax.axvline(xd, color=MUTED, linestyle="--", linewidth=1, zorder=1)
        ax.text(xd, 1.01, lab, ha="center", fontsize=8.5, color=MUTED,
                transform=ax.get_xaxis_transform())
    ax.set_yticks([])
    ax.set_xlabel(r"landed design point $\hat{x}$", fontsize=10)
    fig.suptitle("Round 6 — where does a scalar point target land?\n"
                 "dot = one restart's $\\hat{x}$ (seeds pooled); gray = round-2 MMD references",
                 fontsize=10, x=0.5)
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.grid(axis="x", alpha=0.18)
    fig.tight_layout(rect=(0, 0, 0.72, 0.90))
    fig_path = os.path.join(_HERE, "figures", "fig8_pointwise.png")
    fig.savefig(fig_path, dpi=150)
    plt.close(fig)
    L.append("Figure: `figures/fig8_pointwise.png`")

    out = os.path.join(_HERE, "POINTWISE.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out} and {fig_path}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
